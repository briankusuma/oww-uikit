const fs = require('fs');
const path = require('path');

const ICONS_DIR = path.resolve(__dirname, '../src/assets/icons');
const OUTPUT_FILE = path.resolve(__dirname, '../src/scss/components/_icons.scss');

// Recursively find all SVG files in the icons directory
function getSvgFiles(dir) {
  let results = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(getSvgFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith('.svg')) {
      results.push(fullPath);
    }
  }
  return results;
}

function generateIconsScss() {
  console.log('Generating _icons.scss from SVG assets...');

  if (!fs.existsSync(ICONS_DIR)) {
    console.error(`Error: Icons directory not found at ${ICONS_DIR}`);
    process.exit(1);
  }

  const svgFiles = getSvgFiles(ICONS_DIR);
  console.log(`Found ${svgFiles.length} SVG files.`);

  // Base icon styles
  const lines = [
    '// =============================================================================',
    '// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY',
    '// Generated by scripts/generate-icons-scss.js',
    '// =============================================================================',
    '',
    '[class^="oww-icon--"],',
    '[class*=" oww-icon--"] {',
    '  display: inline-block;',
    '  width: 1em;',
    '  height: 1em;',
    '  background-repeat: no-repeat;',
    '  background-position: center;',
    '  background-size: contain;',
    '  vertical-align: middle;',
    '  flex-shrink: 0;',
    '}',
    ''
  ];

  let count = 0;
  // Sort files for deterministic output
  svgFiles.sort().forEach((file) => {
    const filename = path.basename(file, '.svg');
    const className = `oww-icon--${filename}`;
    const svgContent = fs.readFileSync(file, 'utf8').trim();
    const base64 = Buffer.from(svgContent).toString('base64');
    const dataUri = `data:image/svg+xml;base64,${base64}`;

    lines.push(`.${className} {`);
    lines.push(`  background-image: url("${dataUri}");`);
    lines.push('}');
    lines.push('');
    count++;
  });

  // Ensure target directory exists
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');

  console.log(`Successfully generated ${count} icons in ${OUTPUT_FILE}`);
}

generateIconsScss();
